import {execFileSync} from 'node:child_process';
import {mkdtempSync,rmSync,readFileSync,writeFileSync,copyFileSync,statSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve,basename} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('../',import.meta.url)),dir=mkdtempSync(join(tmpdir(),'foregather-package-'));
try {
  let packed;
  if(process.argv[2]) {
    const archive=resolve(process.argv[2]),filename=basename(archive);
    const files=execFileSync('tar',['-tzf',archive],{encoding:'utf8'}).trim().split('\n').map(name=>({path:name.replace(/^package\//,'')}));
    if(files.some(f=>f.path.startsWith('/')||f.path.split('/').includes('..')))throw Error('Invalid package path');
    copyFileSync(archive,join(dir,filename));packed={filename,files,size:statSync(archive).size};
  } else packed=JSON.parse(execFileSync('npm',['pack','./packages/browser','--json','--pack-destination',dir],{cwd:root,encoding:'utf8'}))[0];
  assert.ok(packed.files.some(f=>f.path==='dist/foregather_wasm_bg.wasm'));
  assert.ok(packed.files.some(f=>f.path==='dist/index.d.ts'));
  assert.ok(packed.files.some(f=>f.path==='THIRD_PARTY_LICENSES.txt'));
  writeFileSync(join(dir,'package.json'),JSON.stringify({type:'module',private:true}));
  execFileSync('npm',['install','--ignore-scripts','--no-audit','--no-fund',join(dir,packed.filename)],{cwd:dir,stdio:'pipe'});
  const script=`import {readFileSync} from 'node:fs';
import {init,createStoredCodec,createLiveOffer,createLivePairing,deriveSpokenWords} from '@forgesworn/foregather-kit';
await init({module_or_path:readFileSync('node_modules/@forgesworn/foregather-kit/dist/foregather_wasm_bg.wasm')});
const codec=createStoredCodec({namespace:'installed.example',baseUrl:'https://resolver.example/i/'});
const now=1800000000,payload=new TextEncoder().encode('installed package');
const sealed=codec.seal({id:'BwcHBwcHBwcHBwcHBwcHBw',payload,expires:now+3600,now});
if(new TextDecoder().decode(codec.open({url:sealed.url,envelope:JSON.stringify(sealed.envelope),now}))!=='installed package')throw Error('Package failed');
const offer=createLiveOffer({namespace:'installed.example',purpose:'bootstrap',now});
const a=createLivePairing({...offer,namespace:'installed.example',purpose:'bootstrap',role:'inviter',now});
const b=createLivePairing({...offer,namespace:'installed.example',purpose:'bootstrap',role:'recipient',now});
const ax=a.start({now}),bx=b.start({now}),ah=ax.hello(),bh=bx.hello();
const ap=ax.finish({peerHello:bh,now}),bp=bx.finish({peerHello:ah,now}),aproof=ap.proof(),bproof=bp.proof();
const ac=ap.confirm({peerProof:bproof,now}),bc=bp.confirm({peerProof:aproof,now});
if(ac.verificationWords({now})!==bc.verificationWords({now}))throw Error('Installed pairing mismatch');
const packet=ac.seal({payload,now});
if(new TextDecoder().decode(bc.open({packet,now}))!=='installed package')throw Error('Installed live transfer failed');
a.dispose();b.dispose();ac.dispose();bc.dispose();
const secret=new Uint8Array(32);secret[31]=1;
if(deriveSpokenWords({secret,context:'test',counter:0})!=='jazz earth glacier')throw Error('Installed spoken mismatch');
`;
  writeFileSync(join(dir,'check.mjs'),script);
  execFileSync(process.execPath,['check.mjs'],{cwd:dir,stdio:'pipe'});
  copyFileSync(join(root,'tests/types/consumer.mts'),join(dir,'consumer.mts'));
  execFileSync(process.execPath,[join(root,'node_modules/typescript/bin/tsc'),'--noEmit','--strict','--target','ES2022','--module','NodeNext','--lib','ES2022,DOM','consumer.mts'],{cwd:dir,stdio:'inherit'});
  const manifest=JSON.parse(readFileSync(join(dir,'node_modules/@forgesworn/foregather-kit/package.json')));
  assert.equal(manifest.license,'MIT');assert.equal(manifest.author,'TheCryptoDonkey');assert.equal(manifest.dependencies,undefined);
  console.log(JSON.stringify({passed:true,isolatedTarballInstall:true,typesIncluded:true,typeScriptConsumerCompiled:true,licencesIncluded:true,packageBytes:packed.size,runtimeJsDependencies:0}));
} finally {rmSync(dir,{recursive:true,force:true});}
